import assert from 'node:assert/strict';
import { copyFile, mkdir, readFile, stat, writeFile } from 'node:fs/promises';
import { build, preview } from 'vite';
import { chromium } from 'playwright';

const outDir = 'artifacts/refactor/bundle/browser-build';
await mkdir('artifacts/refactor/bundle', { recursive: true });
await build({ logLevel: 'error', define: { 'import.meta.env.VITE_MOCK_API': '"true"' }, build: { outDir } });
await copyFile(`${outDir}/index.html`, `${outDir}/app.html`);
const manifest = JSON.parse(await readFile(`${outDir}/.vite/manifest.json`, 'utf8'));
const initial = new Set();
function visit(key) {
  const entry = manifest[key];
  if (initial.has(entry.file)) return;
  initial.add(entry.file);
  for (const dependency of entry.imports || []) visit(dependency);
}
visit(Object.keys(manifest).find(key => manifest[key].isEntry));
for (const file of initial) assert.doesNotMatch(file, /\/(charts|dnd|pdf|xlsx)-/);
const server = await preview({ build: { outDir }, preview: { host: '127.0.0.1', port: 5181, open: false } });
const browser = await chromium.launch({ headless: true });
try {
  const context = await browser.newContext({ viewport: { width: 1366, height: 900 }, acceptDownloads: true });
  await context.route('https://fonts.googleapis.com/**', route => route.fulfill({ contentType: 'text/css', body: '' }));
  await context.addInitScript(() => document.addEventListener('DOMContentLoaded', () => {
    const style = document.createElement('style');
    style.textContent = 'details:has(> summary .lucide-flask-conical){display:none!important}';
    document.head.append(style);
  }));
  const page = await context.newPage();
  page.setDefaultTimeout(30000);
  const errors = [], requests = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('request', request => { if (request.url().endsWith('.js')) requests.push(request.url()); });
  const base = server.resolvedUrls.local[0];
  await page.goto(`${base}login`, { waitUntil: 'domcontentloaded' });
  await page.locator('input[type=email]').fill('demo@nexopdv.local');
  await page.locator('input[type=password]').fill('demo123');
  await page.locator('button[type=submit]').click();
  await page.waitForURL('**/inicio', { waitUntil: 'domcontentloaded' });
  await page.getByRole('heading', { name: 'Seu dia em números' }).waitFor();
  assert.equal(requests.some(url => /\/(charts|dnd|pdf|xlsx)-/.test(url)), false);
  const readDb = () => page.evaluate(() => JSON.parse(localStorage.getItem('nexo:mock-db:v4')));
  const before = await readDb();
  console.log('Login and overview load without charts, drag-and-drop, PDF or Excel.');
  await page.goto(`${base}financeiro`, { waitUntil: 'domcontentloaded' });
  await page.locator('.recharts-surface').first().waitFor();
  assert.ok(requests.some(url => /\/charts-/.test(url)));
  assert.equal(requests.some(url => /\/(dnd|pdf|xlsx)-/.test(url)), false);
  await page.goto(`${base}pdv`, { waitUntil: 'domcontentloaded' });
  await page.locator('.pdv-product-card').first().waitFor();
  assert.equal(requests.some(url => /\/dnd-/.test(url)), false);
  await page.locator('.pdv-product-card').first().click();
  await page.getByRole('button', { name: /^Minimizar/ }).click();
  const parkedSale = page.getByTitle('Abrir esta venda sem precisar minimizar a atual');
  await parkedSale.first().waitFor();
  assert.ok(requests.some(url => /\/dnd-/.test(url)));
  await parkedSale.first().click();
  await page.getByRole('button', { name: /^Minimizar/ }).waitFor();
  assert.equal(await page.getByRole('button', { name: /^Minimizar/ }).isDisabled(), false);
  assert.equal(await parkedSale.count(), 0);
  console.log('Charts and parked-sale controls load on demand and work.');
  await page.goto(`${base}estoque`, { waitUntil: 'domcontentloaded' });
  const excel = page.getByRole('button', { name: 'Excel', exact: true });
  await excel.waitFor();
  assert.equal(requests.some(url => /\/xlsx-/.test(url)), false);
  const excelDownload = page.waitForEvent('download');
  await excel.click();
  const workbook = await excelDownload;
  assert.match(workbook.suggestedFilename(), /\.xlsx$/);
  assert.ok((await stat(await workbook.path())).size > 100);
  assert.ok(requests.some(url => /\/xlsx-/.test(url)));
  await page.goto(`${base}vendas`, { waitUntil: 'domcontentloaded' });
  const pdf = page.getByRole('button', { name: 'Exportar', exact: true });
  await pdf.waitFor();
  assert.equal(requests.some(url => /\/pdf-/.test(url)), false);
  const pdfDownload = page.waitForEvent('download');
  await pdf.click();
  const report = await pdfDownload;
  assert.match(report.suggestedFilename(), /\.pdf$/);
  assert.ok((await stat(await report.path())).size > 100);
  assert.ok(requests.some(url => /\/pdf-/.test(url)));
  assert.deepEqual(await readDb(), before);
  assert.deepEqual(errors, []);
  await writeFile('artifacts/refactor/bundle/browser-requests.json', JSON.stringify({ initial: [...initial], requests }, null, 2));
  console.log('Excel and PDF downloads work on demand; existing demo records are unchanged.');
} finally {
  await browser.close();
  await new Promise(resolve => server.httpServer.close(resolve));
}
