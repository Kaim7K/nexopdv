import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';

const browser = await chromium.launch({ headless: true });
const out = 'artifacts/stock-quantity';
await fs.mkdir(out, { recursive: true });
try {
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
  const page = await context.newPage();
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  page.setDefaultTimeout(10000);
  await page.route('https://fonts.googleapis.com/**', route => route.abort());
  await page.goto('http://127.0.0.1:5177/login', { waitUntil: 'domcontentloaded' });
  await page.locator('input[type=email]').fill('demo@nexopdv.local');
  await page.locator('input[type=password]').fill('demo123');
  await page.locator('button[type=submit]').click();
  await page.waitForURL('**/inicio');
  await page.goto('http://127.0.0.1:5177/estoque', { waitUntil: 'domcontentloaded' });
  const quantity = page.locator('input[aria-label^="Qtd. de"]').first();
  await quantity.waitFor();
  const headers = await page.locator('.stock-data-table th').allTextContents();
  assert.deepEqual(headers.slice(0, 5).map(text => text.trim()), ['Produto', 'Categoria', 'Qtd.', 'Venda', 'Cód. barras']);
  const original = await quantity.inputValue();
  const before = await page.evaluate(() => localStorage.getItem('nexo:mock-db:v4'));
  await quantity.fill('19'); await page.keyboard.press('Escape');
  assert.equal(await quantity.inputValue(), original);
  await quantity.fill('-1'); await page.getByLabel('Pesquisar produtos', { exact: true }).focus();
  assert.equal(await quantity.inputValue(), original);
  await quantity.fill(''); await page.getByLabel('Pesquisar produtos', { exact: true }).focus();
  assert.equal(await quantity.inputValue(), original);
  assert.equal(await page.evaluate(() => localStorage.getItem('nexo:mock-db:v4')), before);
  await page.evaluate(async () => {
    const { nexoApi } = await import('/src/api/nexoApi.js');
    window.__quantityApi = nexoApi;
    window.__originalBulk = nexoApi.stock.bulkUpdate;
    window.__calls = [];
    nexoApi.stock.bulkUpdate = async (...args) => {
      window.__calls.push(performance.now());
      await new Promise(resolve => setTimeout(resolve, 300));
      return window.__originalBulk(...args);
    };
  });
  await quantity.fill('12.125');
  const start = await page.evaluate(() => performance.now());
  await page.getByLabel('Pesquisar produtos', { exact: true }).focus();
  await page.waitForFunction(() => window.__calls.length === 1);
  assert.ok(await page.evaluate(started => window.__calls[0] - started < 800, start), 'Quantity should save immediately, without the 900ms debounce');
  assert.ok(await quantity.isDisabled(), 'Fields are locked during persistence');
  await page.getByRole('status').filter({ hasText: 'Salvo' }).waitFor();
  await page.reload({ waitUntil: 'domcontentloaded' });
  await quantity.waitFor(); assert.equal(await quantity.inputValue(), '12.125');
  await page.screenshot({ path: `${out}/desktop.png`, animations: 'disabled' });
  await page.evaluate(async () => {
    const { nexoApi } = await import('/src/api/nexoApi.js');
    window.__quantityApi = nexoApi;
    window.__originalBulk = nexoApi.stock.bulkUpdate;
    window.__failedCalls = 0;
    nexoApi.stock.bulkUpdate = async () => { window.__failedCalls += 1; throw new Error('Falha simulada ao salvar estoque'); };
  });
  await quantity.fill('14'); await page.keyboard.press('Enter');
  await page.getByText('Falha simulada ao salvar estoque', { exact: true }).waitFor();
  const retry = page.getByRole('button', { name: 'Salvar 1', exact: true });
  await retry.waitFor(); await page.waitForTimeout(1200);
  assert.equal(await page.evaluate(() => window.__failedCalls), 1, 'Do not loop after a failed save');
  await page.screenshot({ path: `${out}/failure-pending.png`, animations: 'disabled' });
  await page.evaluate(() => { window.__quantityApi.stock.bulkUpdate = window.__originalBulk; });
  await retry.click(); await page.getByRole('status').filter({ hasText: 'Salvo' }).waitFor();
  await page.reload({ waitUntil: 'domcontentloaded' });
  await quantity.waitFor(); assert.equal(await quantity.inputValue(), '14');
  await quantity.fill('0'); await page.keyboard.press('Tab');
  await page.getByRole('status').filter({ hasText: 'Salvo' }).waitFor();
  await page.reload({ waitUntil: 'domcontentloaded' });
  await quantity.waitFor(); assert.equal(await quantity.inputValue(), '0');
  await page.setViewportSize({ width: 390, height: 844 });
  await page.waitForTimeout(300);
  assert.ok(await page.locator('.stock-mobile-record').first().isVisible());
  await page.screenshot({ path: `${out}/mobile.png`, animations: 'disabled' });
  assert.deepEqual(errors, []);
  await context.close();
  console.log('Column order, immediate blur save, fractions, zero, Escape, invalid values, failure, manual retry and mobile passed.');
} finally { await browser.close(); }
